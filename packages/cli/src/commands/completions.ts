import type { CliIo } from '../index.js';

/** Shells `keylease completions` can render. */
export const COMPLETION_SHELLS = ['bash', 'zsh', 'fish'] as const;
export type CompletionShell = (typeof COMPLETION_SHELLS)[number];

/** Values accepted by `--network`, shared by all three completion scripts. */
export const COMPLETION_NETWORKS = ['testnet', 'mainnet', 'local'] as const;

