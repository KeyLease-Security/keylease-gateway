export const COMPLETION_COMMAND_NAMES: readonly string[] = COMPLETION_COMMANDS.map(
  (command) => command.name,
);

/** Every option any command accepts, in table order (globals first). */
export const COMPLETION_FLAGS: readonly string[] = [
  ...GLOBAL_FLAGS,
  ...new Set(
    COMPLETION_COMMANDS.flatMap((command) => command.flags).filter(
      (flag) => !(GLOBAL_FLAGS as readonly string[]).includes(flag),
    ),
  ),
];

function descriptionFor(flag: string): string {
  return FLAG_DESCRIPTIONS[flag] ?? 'option';
}

function banner(shell: CompletionShell): string {
  const commands = COMPLETION_COMMAND_NAMES.join(' ');
  const flags = COMPLETION_FLAGS.filter((flag) => flag.startsWith('--')).join(' ');
  return [
    `# keylease completion for ${shell}. Generated by \`keylease completions ${shell}\`.`,
    `# Commands: ${commands}`,
    `# Options: ${flags}`,
    `# Networks: ${COMPLETION_NETWORKS.join(' ')}`,
    `# Shells: ${COMPLETION_SHELLS.join(' ')}`,
  ].join('\n');
}

function renderBash(): string {
  return `${banner('bash')}
# Install: source <(keylease completions bash)   # current shell
#          keylease completions bash > /etc/bash_completion.d/keylease

_keylease_completions() {
  local cur prev
  cur="\${COMP_WORDS[COMP_CWORD]}"
  prev="\${COMP_WORDS[COMP_CWORD-1]}"

  case "\${prev}" in
    --network) COMPREPLY=( $(compgen -W "${COMPLETION_NETWORKS.join(' ')}" -- "\${cur}") ); return 0 ;;
    completions) COMPREPLY=( $(compgen -W "${COMPLETION_SHELLS.join(' ')}" -- "\${cur}") ); return 0 ;;
  esac

  if [[ "\${cur}" == -* ]]; then
    COMPREPLY=( $(compgen -W "${COMPLETION_FLAGS.join(' ')}" -- "\${cur}") )
    return 0
  fi

  COMPREPLY=( $(compgen -W "${COMPLETION_COMMAND_NAMES.join(' ')}" -- "\${cur}") )
}

complete -F _keylease_completions keylease`;
}

function zshArgSpec(flag: string): string {
  const description = descriptionFor(flag);
  if (!VALUE_FLAGS.includes(flag)) return `'${flag}[${description}]'`;
  const action =
    flag === '--network' ? `:network:(${COMPLETION_NETWORKS.join(' ')})` : `:${flag.slice(2)}:`;
  return `'${flag}[${description}]${action}'`;
}

function renderZsh(): string {
  const commandLines = COMPLETION_COMMANDS.map(
    (command) => `    '${command.name}:${command.summary}'`,
  ).join('\n');

  const argBranches = COMPLETION_COMMANDS.filter((command) => command.flags.length > 0)
    .map((command) => {
      const specs = command.flags.map((flag) => `            ${zshArgSpec(flag)}`).join(' \\\n');
      return `        ${command.name})\n          _arguments \\\n${specs}\n          ;;`;
    })
    .join('\n');

  return `#compdef keylease
${banner('zsh')}
# Install: keylease completions zsh > "\${fpath[1]}/_keylease"

_keylease() {
  local -a commands
  commands=(
${commandLines}
  )

  _arguments -C \\
    '1:command:->command' \\
    '*::arg:->args'

  case $state in
    command)
      _describe -t commands 'keylease command' commands
      ;;
    args)
      case $words[1] in
        completions)
          _values 'shell' ${COMPLETION_SHELLS.join(' ')}
          ;;
${argBranches}
      esac
      ;;
  esac
}

_keylease "$@"`;
}

function renderFish(): string {
  const subcommands = COMPLETION_COMMANDS.map(
    (command) =>
      `complete -c keylease -f -n '__fish_use_subcommand' -a ${command.name} -d '${command.summary}'`,
  ).join('\n');

  const argCompletions = COMPLETION_COMMANDS.filter((command) => command.flags.length > 0)
    .map((command) => {
      const options = command.flags
        .map((flag) => {
          const name = flag.slice(2);
          if (!VALUE_FLAGS.includes(flag)) {
            return `complete -c keylease -n '__fish_seen_subcommand_from ${command.name}' -l ${name} -d '${descriptionFor(flag)}'`;
          }
          const values =
            flag === '--network' ? ` -x -a '${COMPLETION_NETWORKS.join(' ')}'` : ' -r';
          return `complete -c keylease -n '__fish_seen_subcommand_from ${command.name}' -l ${name}${values} -d '${descriptionFor(flag)}'`;
        })
        .join('\n');
      return options;
    })
    .join('\n');

  return `${banner('fish')}
# Install: keylease completions fish > ~/.config/fish/completions/keylease.fish

complete -c keylease -f
complete -c keylease -s h -l help -d '${descriptionFor('--help')}'
complete -c keylease -s V -l version -d '${descriptionFor('--version')}'
${subcommands}
complete -c keylease -n '__fish_seen_subcommand_from completions' -x -a '${COMPLETION_SHELLS.join(' ')}'
${argCompletions}`;
}

/** True when `value` is one of the supported shells. */
export function isCompletionShell(value: string): value is CompletionShell {
  return (COMPLETION_SHELLS as readonly string[]).includes(value);
}

/** Renders the static completion script for `shell` from the table above. */
export function renderCompletions(shell: CompletionShell): string {
  switch (shell) {
    case 'bash':
      return renderBash();
    case 'zsh':
      return renderZsh();
    case 'fish':
      return renderFish();
  }
}

export interface CompletionsArgs {
  shell: string;
}

/**
 * `keylease completions <shell>` prints a completion script on stdout so it can
 * be sourced or redirected without writing files itself.
 */
export async function completionsCommand(args: CompletionsArgs, io: CliIo): Promise<number> {
  if (!isCompletionShell(args.shell)) {
    throw new CliError(
      `unsupported shell "${args.shell}" (supported: ${COMPLETION_SHELLS.join(', ')})`,
    );
  }
  io.out(renderCompletions(args.shell));
  return 0;
}
