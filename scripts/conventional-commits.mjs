/**
 * Conventional Commits rules for pull request titles.
 *
 * One source of truth for three consumers:
 *   * `commitlint.config.mjs` — the check CI runs on every pull request,
 *   * `scripts/pr-title-suggestion.mjs` — the copy-pasteable corrected title
 *     printed when that check fails,
 *   * `scripts/conventional-commits.test.mjs` — the tests for both.
 *
 * Only the pull request title is validated. The accepted header is
 * `<type>(<scope>)!: <subject>` where the scope and the breaking-change `!`
 * are optional. Scopes are deliberately **not** restricted to a list: the
 * repository currently uses `proxy`, `contract`, `cli` and `ci`, and a new
 * area must not need a workflow change before it can be used in a title.
 */

/** Accepted commit types, taken from the repository's own history. */
export const TYPES = [
  'feat',
  'fix',
  'docs',
  'ci',
  'chore',
  'test',
  'refactor',
  'perf',
  'build',
  'revert',
];

/** One-line meaning of each type, used by CONTRIBUTING.md and the suggestion output. */
export const TYPE_NOTES = {
  feat: 'a user-visible feature or capability',
  fix: 'a bug fix, including a security fix',
  docs: 'documentation only (README, CONTRIBUTING, SECURITY, docs/)',
  ci: 'workflows, tooling and release automation',
  chore: 'maintenance that changes no behaviour (dependencies, metadata)',
  test: 'adding or repairing tests only',
  refactor: 'a change that neither fixes a bug nor adds a feature',
  perf: 'a performance improvement',
  build: 'the build, packaging or lockfile setup',
  revert: 'reverting a previous commit',
};

/** Maximum header length, matching the `header-max-length` commitlint rule. */
export const MAX_HEADER_LENGTH = 100;

/** Actors whose generated PR titles are reviewed on content instead. */
export const EXEMPT_ACTORS = ['dependabot[bot]'];

const HEADER_PATTERN = /^([A-Za-z][A-Za-z0-9-]*)(?:\(([^()]*)\))?(!)?: (.+)$/;
const MERGE_TITLE_PATTERN = /^Merge (pull request|branch|remote-tracking|tag)\b/;
const SCOPE_PATTERN = /^[a-z0-9][a-z0-9 /-]*$/;

const TYPE_SYNONYMS = new Map([
  ['feature', 'feat'],
  ['features', 'feat'],
  ['add', 'feat'],
  ['bug', 'fix'],
  ['bugfix', 'fix'],
  ['hotfix', 'fix'],
  ['security', 'fix'],
  ['doc', 'docs'],
  ['documentation', 'docs'],
  ['deps', 'chore'],
  ['dependency', 'chore'],
  ['dependencies', 'chore'],
  ['release', 'chore'],
  ['workflow', 'ci'],
  ['workflows', 'ci'],
  ['actions', 'ci'],
  ['pipeline', 'ci'],
  ['tests', 'test'],
  ['testing', 'test'],
  ['refactoring', 'refactor'],
  ['performance', 'perf'],
]);

/** Keyword → type fallbacks, checked in order, when a title carries no type. */
const TYPE_INFERENCE = [
  [/\b(docs?|documentation|readme|runbook|guide|checklist)\b/i, 'docs'],
  [/\b(ci|workflows?|actions?|pipelines?|lint|ci\/cd)\b/i, 'ci'],
  [/\b(tests?|testing|coverage|specs?)\b/i, 'test'],
  [/\b(fix|fixes|fixed|bug|bugs|repair|broken|crash|error|regression)\b/i, 'fix'],
  [/\b(refactor|rename|simplify|cleanup|tidy)\b/i, 'refactor'],
  [/\b(perf|performance|speed|latency|optimi[sz]e)\b/i, 'perf'],
  [/\b(bump|upgrade|deps|dependencies|release)\b/i, 'chore'],
  [/\b(add|adds|implement|introduce|support|create|new|feature)\b/i, 'feat'],
];

/** True for titles generated by GitHub when a merge commit becomes a PR title. */
export function isExemptTitle(title) {
  return typeof title === 'string' && MERGE_TITLE_PATTERN.test(title.trim());
}

/** True for bots whose PR titles are not authored by a contributor. */
export function isExemptActor(actor) {
  return typeof actor === 'string' && EXEMPT_ACTORS.includes(actor);
}

/** Splits a title into its Conventional Commit parts, or returns null. */
export function parseTitle(title) {
  if (typeof title !== 'string') return null;
  const match = HEADER_PATTERN.exec(title.trim());
  if (match === null) return null;
  const type = match[1];
  const scope = match[2];
  const subject = match[4];
  return {
    type,
    scope: scope === undefined || scope.trim() === '' ? null : scope,
    breaking: match[3] === '!',
    subject,
  };
}

/**
 * Validates a PR title against the same rules `commitlint.config.mjs` applies.
 * Returns every reason instead of stopping at the first one so a contributor
 * can fix the title in one edit.
 */
export function validateTitle(title) {
  const text = typeof title === 'string' ? title.trim() : '';
  if (text.length === 0) {
    return { ok: false, parsed: null, reasons: ['the title is empty'] };
  }
  const parsed = parseTitle(text);
  if (parsed === null) {
    return {
      ok: false,
      parsed: null,
      reasons: [
        'expected "<type>(<scope>): <subject>", for example "feat(proxy): add request validation"',
      ],
    };
  }

  const reasons = [];
  const lowerType = parsed.type.toLowerCase();
  if (!TYPES.includes(lowerType)) {
    reasons.push(`"${parsed.type}" is not an accepted type (${TYPES.join(', ')})`);
  }
  if (parsed.type !== lowerType) reasons.push('the type must be lower-case');
  if (parsed.scope !== null && !SCOPE_PATTERN.test(parsed.scope)) {
    reasons.push('the scope must be lower-case words, digits, spaces, "/" or "-"');
  }
  if (parsed.subject.trim().length === 0) reasons.push('the subject is empty');
  if (parsed.subject.trim().endsWith('.')) reasons.push('the subject must not end with a period');
  if (text.length > MAX_HEADER_LENGTH) {
    reasons.push(`the title is ${text.length} characters; keep it within ${MAX_HEADER_LENGTH}`);
  }

  return { ok: reasons.length === 0, parsed, reasons };
}

function normalizeType(token) {
  if (typeof token !== 'string') return null;
  const cleaned = token.trim().toLowerCase().replace(/^[^\w]+/, '').replace(/[^\w]+$/, '');
  if (TYPE_SYNONYMS.has(cleaned)) return TYPE_SYNONYMS.get(cleaned);
  return TYPES.includes(cleaned) ? cleaned : null;
}

function inferType(text) {
  for (const [pattern, type] of TYPE_INFERENCE) {
    if (pattern.test(text)) return type;
  }
  return 'chore';
}

function normalizeScope(raw) {
  if (typeof raw !== 'string') return null;
  const scope = raw
    .trim()
    .toLowerCase()
    .replace(/\s+/g, '-')
    .replace(/[^a-z0-9/-]+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^[-/]+|[-/]+$/g, '');
  return scope.length === 0 ? null : scope;
}

function normalizeSubject(raw) {
  const subject = raw.trim().replace(/\s+/g, ' ').replace(/\.+$/, '');
  if (subject.length === 0) return 'describe the change';
  const first = subject[0];
  const second = subject[1];
  // Lower-case the first letter unless the word looks like an acronym.
  if (first === first.toUpperCase() && (second === undefined || second === second.toLowerCase())) {
    return first.toLowerCase() + subject.slice(1);
  }
  return subject;
}

/**
 * Builds the title a contributor can paste over the rejected one. The result
 * is always a title `validateTitle` accepts, unless the original is longer than
 * `MAX_HEADER_LENGTH` (a suggestion is never truncated mid-sentence).
 */
export function buildSuggestion(title) {
  const text = typeof title === 'string' ? title.trim().replace(/\s+/g, ' ') : '';
  if (text.length === 0) {
    return { title: '', notes: ['there is no PR title to correct'] };
  }
  if (isExemptTitle(text)) return { title: text, notes: [] };

  const notes = [];
  const parsed = parseTitle(text);
  let type;
  let scope = null;
  let breaking = false;
  let subject;

  if (parsed !== null) {
    type = normalizeType(parsed.type);
    if (type === null) {
      type = inferType(parsed.subject);
      notes.push(`the type "${parsed.type}" is not accepted, so "${type}" was inferred`);
    }
    scope = normalizeScope(parsed.scope ?? '');
    breaking = parsed.breaking;
    subject = parsed.subject;
  } else {
    const attempt = /^([^:]{1,40}):\s*(.+)$/.exec(text);
    const candidate = attempt === null ? '' : attempt[1];
    const rest = attempt === null ? text : attempt[2];
    const bracketed = /^\[([^\]]{1,40})\]\s*(.+)$/.exec(rest);
    type = normalizeType(candidate) ?? inferType(rest);
    if (normalizeType(candidate) === null) {
      notes.push(`no accepted type was present, so "${type}" was inferred`);
    }
    if (bracketed !== null) {
      scope = normalizeScope(bracketed[1]);
      subject = bracketed[2];
    } else {
      subject = rest;
    }
  }

  const suggestion = `${type}${scope === null ? '' : `(${scope})`}${breaking ? '!' : ''}: ${normalizeSubject(subject)}`;
  if (suggestion.length > MAX_HEADER_LENGTH) {
    notes.push(
      `the suggestion is ${suggestion.length} characters; shorten the subject to ${MAX_HEADER_LENGTH} or fewer`,
    );
  }
  return { title: suggestion, notes };
}
